// 공용 메일함 — 키워드 분류 규칙 단위 테스트.
//   순수 함수만 검증합니다(네트워크·DB·AI 접근 없음).
//   실제로 관찰된 제목·발신자를 표본으로 씁니다.
import { classifyByKeyword } from "../lib/mailKeywordRules";

function assert(cond: boolean, message: string) {
  if (!cond) throw new Error(message);
}

let checked = 0;

// 기대값이 null 이면 "AI 에 넘긴다" 는 뜻입니다.
function eq(
  subject: string,
  fromName: string,
  expected: string | null,
  note: string,
) {
  const got = classifyByKeyword(subject, fromName);
  assert(
    got === expected,
    `${note}\n  제목: ${subject}\n  발신: ${fromName}\n  기대: ${expected} / 실제: ${got}`,
  );
  checked++;
}

// --- 방카 / 토요늘봄 ---------------------------------------------------
eq("26방카 수학운영계획서", "권수현", "방카", "방카 — 약칭");
eq("부산청소년방과후아카데미연합회 정기회의", "연합회", "방카", "방카 — 연합회");
eq("9월 코딩 수업 운영 지도안", "강사", null, "방카 — 키워드 없으면 AI 로");
eq("토요일 통기타 대체강사입니다!", "강사", "토요늘봄", "토요늘봄 — 토요");
eq(
  "늘봄 9월 10월 비보이, 유튜브 강의 계획서",
  "강사",
  "토요늘봄",
  "토요늘봄 — 늘봄",
);
