eq("전기요금 청구서 안내", "업체", "회계", "회계 — 청구서");
// "정산"·"계약서"·"견적서" 는 시설 공사·대관 메일에도 붙어 규칙에서
//   뺐습니다 — 잘못된 칸으로 보내느니 AI 에 맡깁니다.
eq("체험활동 정산 자료 요청", "업체", null, "정산 — 키워드로 잡지 않음");
