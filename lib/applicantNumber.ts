// 접수번호 표기 공용 헬퍼 — 의존성 없는 순수 모듈(서버·클라이언트 공용).
//   * 대외 공고(면접 대상자·최종 합격자)는 응시자 보호를 위해 성명을 마스킹하고
//     접수번호는 "뒷 4자리"만 공개합니다. 지원자가 본인을 확인하는 유일한 키이므로
//     공고 빌더(lib/recruitmentDocBuilders.ts)와 지원 화면(ApplyForm)이 반드시
//     같은 값을 보여줘야 합니다. 그래서 slice 로직을 여기 한 곳에 둡니다.
// =====================================================================

// 접수번호 뒷 4자리. 값이 없거나 4자 미만이면 있는 만큼 그대로 반환합니다.
export function applicantNumberLast4(
  applicantNumber: string | null | undefined
): string {
  return (applicantNumber ?? "").slice(-4);
}
